export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => getInitialLanguage())

  const setLanguage = (lang) => {
    if (!SUPPORTED_LANGS.includes(lang)) return
    setLanguageState(lang)
    try {
      localStorage.setItem(STORAGE_KEY, lang)
    } catch (_) {}
  }

  useEffect(() => {
    try {
      document.documentElement.lang = language === 'en' ? 'en' : 'fr'
      document.title = translations[language]?.['title.default'] || 'SantéClaire'
    } catch (_) {}
  }, [language])

  /**
   * Traduction avec fallback propre :
   * 1. Clé dans la langue courante
   * 2. Clé dans l'autre langue (fr/en)
   * 3. Clé brute (évité au maximum)
   */
  const t = (key, vars = {}) => {
    const fallbackLang = language === 'en' ? 'fr' : 'en'
    let str = translations[language]?.[key]
      || translations[fallbackLang]?.[key]
      || key
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v ?? ''))
    })
    return str
  }

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLanguage() {
  return useContext(LanguageContext)
}
