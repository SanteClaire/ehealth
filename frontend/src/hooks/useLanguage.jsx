const STORAGE_KEY = 'santeclaire_lang'
const SUPPORTED_LANGS = ['fr', 'en']
const DEFAULT_LANG = 'fr'
const LanguageContext = createContext()

/**
 * Détecte la langue préférée du navigateur.
 * Utilisée uniquement au premier chargement si aucune préférence n'est stockée.
 */
function getBrowserLanguage() {
  try {
    if (typeof navigator === 'undefined') return DEFAULT_LANG
    const lang = (navigator.language || navigator.userLanguage || '').toLowerCase()
    const code = lang.split(/[-_]/)[0] || ''
    if (code === 'fr') return 'fr'
    if (code === 'en') return 'en'
  } catch (_) {}
  return 'en'
}

/**
 * Retourne la langue à utiliser : préférence stockée > langue navigateur > défaut.
 */
function getInitialLanguage() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY)
    if (stored && SUPPORTED_LANGS.includes(stored)) return stored
  } catch (_) {}
  try {
    return getBrowserLanguage()
  } catch (_) {
    return DEFAULT_LANG
  }
}

